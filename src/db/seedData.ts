const nowMs = Date.now();
const nowIso = new Date(nowMs).toISOString();
const todayAt = (hour: number, min: number) => {
  const d = new Date(nowMs);
  d.setHours(hour, min, 0, 0);
  if (d.getTime() > nowMs) {
    d.setTime(Math.max(nowMs - (hour + 1) * 300_000, new Date(nowMs).setHours(0, min, 0, 0)));
  }
  return d.toISOString();
};
const daysAgoAt = (days: number, hour: number, min: number) => {
  const d = new Date(nowMs - days * 86400_000);
  d.setHours(hour, min, 0, 0);
  return d.toISOString();
};
const minsAgo = (m: number) => new Date(nowMs - m * 60_000).toISOString();

